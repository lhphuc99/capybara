import 'dart:collection';
import 'dart:typed_data';

/// How much of a value [serialize] keeps. The defaults are the JS SDK's, so the UI reads both the same way.
final class SerializeOptions {
  const SerializeOptions({
    this.maxDepth = 6,
    this.maxKeys = 100,
    this.maxItems = 100,
    this.maxString = 10000,
    this.maxNodes = 2000,
  });

  final int maxDepth;
  final int maxKeys;
  final int maxItems;
  final int maxString;

  /// Objects visited per call, which stops runaway graphs.
  final int maxNodes;
}

// The largest integer a JS number holds exactly; bigger ones go as their digits, or the UI would round them.
const int _maxSafeInteger = 9007199254740991;

/// Turns a Dart value into the JSON-safe form Capybara's protocol calls a SerializedValue: what JSON can carry
/// as it is, the rest as objects with a `$t` tag. Never throws.
Object? serialize(Object? value, [SerializeOptions options = const SerializeOptions()]) {
  return _Walker(options).walk(value, 0);
}

final class _Walker {
  _Walker(this.options);

  final SerializeOptions options;
  // Ancestors only, so shared references are repeated and only true cycles are marked.
  final Set<Object> _ancestors = HashSet.identity();
  int _nodes = 0;

  Object? walk(Object? value, int depth) {
    switch (value) {
      case null || bool():
        return value;
      case String():
        return value.length > options.maxString
            ? {r'$t': 'string', 'v': value.substring(0, options.maxString), 'length': value.length}
            : value;
      case int():
        return value > _maxSafeInteger || value < -_maxSafeInteger ? {r'$t': 'number', 'v': '$value'} : value;
      case double():
        if (value.isNaN) return {r'$t': 'number', 'v': 'NaN'};
        if (value == double.infinity) return {r'$t': 'number', 'v': 'Infinity'};
        if (value == double.negativeInfinity) return {r'$t': 'number', 'v': '-Infinity'};
        if (value == 0 && value.isNegative) return {r'$t': 'number', 'v': '-0'};
        return value;
      case BigInt():
        return {r'$t': 'bigint', 'v': value.toString()};
      case Function():
        return {r'$t': 'function', 'name': _functionName(value)};
      case Enum():
        return {r'$t': 'node', 'v': '${value.runtimeType}.${value.name}'};
      case DateTime():
        return {r'$t': 'date', 'v': isoUtc(value)};
      case RegExp():
        return {r'$t': 'regexp', 'v': '/${value.pattern}/${_flags(value)}'};
      case Symbol():
        return {r'$t': 'symbol', 'v': value.toString()};
      case Duration() || Uri() || Type():
        return {r'$t': 'node', 'v': value.toString()};
      case StackTrace():
        return {r'$t': 'node', 'v': value.toString()};
      case TypedData():
        return {r'$t': 'binary', 'name': '${value.runtimeType}', 'size': value.lengthInBytes};
      case Future():
        return {r'$t': 'object', 'name': 'Future', 'props': <String, Object?>{}};
      case Stream():
        return {r'$t': 'object', 'name': 'Stream', 'props': <String, Object?>{}};
    }
    final object = value;
    if (_ancestors.contains(object)) return {r'$t': 'circular'};
    if (depth >= options.maxDepth || ++_nodes > options.maxNodes) return {r'$t': 'limit', 'name': _describe(object)};
    _ancestors.add(object);
    try {
      return _walkObject(object, depth);
    } catch (error) {
      return {r'$t': 'error', 'name': 'Error', 'message': 'Could not read this value: ${_safeString(error)}'};
    } finally {
      _ancestors.remove(object);
    }
  }

  Object? _walkObject(Object object, int depth) {
    if (object is List) {
      final n = object.length < options.maxItems ? object.length : options.maxItems;
      final items = [for (var i = 0; i < n; i++) walk(object[i], depth + 1)];
      return object.length > n ? {r'$t': 'array', 'items': items, 'length': object.length} : items;
    }
    if (object is Map) {
      if (object.keys.every((key) => key is String)) return _walkProps(object.cast<String, Object?>(), depth);
      final entries = <List<Object?>>[];
      for (final entry in object.entries) {
        if (entries.length >= options.maxItems) break;
        entries.add([walk(entry.key, depth + 1), walk(entry.value, depth + 1)]);
      }
      return {r'$t': 'map', 'entries': entries, 'size': object.length};
    }
    if (object is Set) {
      return {
        r'$t': 'set',
        'values': [for (final item in object.take(options.maxItems)) walk(item, depth + 1)],
        'size': object.length,
      };
    }
    if (object is Error || object is Exception) return errorValue(object, depth: depth);
    // Classes generated by json_serializable or freezed, and many others, describe themselves this way.
    final json = _tryCall(() => (object as dynamic).toJson());
    if (json.ok) {
      final walked = walk(json.value, depth);
      return walked is Map && !walked.containsKey(r'$t')
          ? {r'$t': 'object', 'name': _typeName(object), 'props': walked}
          : {
              r'$t': 'object',
              'name': _typeName(object),
              'props': {'toJson()': walked},
            };
    }
    // Equatable's fields, which Bloc states often extend.
    final props = _tryCall(() => (object as dynamic).props);
    if (props.ok && props.value is List) {
      final list = props.value as List;
      return {
        r'$t': 'object',
        'name': _typeName(object),
        'props': {for (var i = 0; i < list.length && i < options.maxKeys; i++) '$i': walk(list[i], depth + 1)},
      };
    }
    return {r'$t': 'node', 'v': _safeString(object)};
  }

  Map<String, Object?> _walkProps(Map<String, Object?> map, int depth) {
    final props = <String, Object?>{};
    for (final entry in map.entries.take(options.maxKeys)) {
      props[entry.key] = walk(entry.value, depth + 1);
    }
    final more = map.length - props.length;
    if (more == 0 && !props.containsKey(r'$t')) return props;
    return {r'$t': 'object', 'props': props, if (more > 0) 'more': more};
  }

  /// An error or exception, with its stack when it carries one.
  Map<String, Object?> errorValue(Object error, {StackTrace? stack, int depth = 0}) {
    final trace = stack ?? (error is Error ? error.stackTrace : null);
    final text = trace?.toString();
    final name = _typeName(error);
    final message = _safeString(error);
    return {
      r'$t': 'error',
      'name': name,
      // `Exception('x')` reads "Exception: x", and the UI puts the name in front already.
      'message': message.startsWith('$name: ') ? message.substring(name.length + 2) : message,
      if (text != null && text.isNotEmpty)
        'stack': text.length > options.maxString ? text.substring(0, options.maxString) : text,
    };
  }

  String _describe(Object object) => switch (object) {
    List() => 'List(${object.length})',
    Map() => 'Map(${object.length})',
    Set() => 'Set(${object.length})',
    _ => _typeName(object),
  };
}

/// An error value for a thrown object and its stack, as [serialize] would describe the object.
Map<String, Object?> serializeError(Object error, [StackTrace? stack]) {
  return _Walker(const SerializeOptions()).errorValue(error, stack: stack);
}

/// `2026-10-28T03:29:36.123Z`: what JS's `Date.prototype.toISOString` gives, milliseconds and all.
String isoUtc(DateTime time) {
  final utc = time.toUtc();
  String two(int n) => n.toString().padLeft(2, '0');
  final year = utc.year >= 0 && utc.year <= 9999 ? utc.year.toString().padLeft(4, '0') : utc.year.toString();
  return '$year-${two(utc.month)}-${two(utc.day)}T${two(utc.hour)}:${two(utc.minute)}:${two(utc.second)}.'
      '${utc.millisecond.toString().padLeft(3, '0')}Z';
}

/// `_Exception` is what `Exception('…')` is; the leading underscore of private classes says nothing to a reader.
String _typeName(Object object) {
  final name = object.runtimeType.toString();
  return name.startsWith('_') && name.length > 1 ? name.substring(1) : name;
}

String _flags(RegExp regExp) => [
  if (!regExp.isCaseSensitive) 'i',
  if (regExp.isMultiLine) 'm',
  if (regExp.isDotAll) 's',
  if (regExp.isUnicode) 'u',
].join();

String _functionName(Function function) {
  final text = _safeString(function);
  // "Closure: () => void from Function 'load': static." Private names carry their library's key: '_load@20362634'.
  final name = RegExp(r"from Function '([^']+)'").firstMatch(text)?.group(1);
  return name?.replaceAll(RegExp(r'@\d+'), '') ?? 'anonymous';
}

String _safeString(Object? value) {
  try {
    return value.toString();
  } catch (_) {
    return 'Instance of ${value.runtimeType}';
  }
}

({bool ok, Object? value}) _tryCall(Object? Function() call) {
  try {
    return (ok: true, value: call());
  } on NoSuchMethodError {
    return (ok: false, value: null);
  } catch (_) {
    return (ok: false, value: null);
  }
}
